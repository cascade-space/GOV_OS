# 1. Health & Policy Check
Write-Host "[1/5] Verifying SLA Policy Configuration in PostgreSQL..." -ForegroundColor Yellow
$policies = docker exec -i govos-postgres psql -U govos_user -d govos_db -c "
SELECT category, priority, resolution_hours, warning_threshold_ratio, escalation_level_1_hours, escalation_level_2_hours
